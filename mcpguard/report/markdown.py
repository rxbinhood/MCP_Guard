"""Markdown report for humans (PR comments, tickets, chat)."""

from __future__ import annotations

from datetime import UTC, datetime

from mcpguard.findings import ScanResult, Severity

_ICON = {"CRITICAL": "🟥", "HIGH": "🟧", "MEDIUM": "🟨", "LOW": "🟦", "INFO": "⬜"}
_VERDICT = {"PASS": "✅ PASS", "WARN": "⚠️ WARN", "FAIL": "❌ FAIL"}


def _fence(text: str) -> str:
    fence = "````" if "```" in text else "```"
    return f"{fence}\n{text.strip()}\n{fence}"


def render_markdown(result: ScanResult) -> str:
    when = datetime.fromtimestamp(result.started_at, UTC).strftime("%Y-%m-%d %H:%M UTC")
    counts = result.counts()
    lines = [
        f"# MCPGuard report: {result.server_name}",
        "",
        f"**Verdict:** {_VERDICT[result.verdict.value]}  ",
        f"**Risk score:** {result.risk_score}/100  ",
        f"**Target:** `{result.target}`  ",
        f"**Scanned:** {when}  ",
        f"**Manifest source:** {result.manifest.method if result.manifest else 'n/a'}"
        f" ({len(result.manifest.tools) if result.manifest else 0} tools)",
        "",
        "| Severity | Count |",
        "|---|---|",
        *[f"| {_ICON[s.value]} {s.value} | {counts[s.value]} |" for s in Severity],
        "",
    ]
    if result.engines:
        lines += ["## Engines", ""]
        for name, info in result.engines.items():
            status = info.get("status", "?") if isinstance(info, dict) else str(info)
            detail = info.get("detail", "") if isinstance(info, dict) else ""
            lines.append(f"- **{name}**: {status}{f' ({detail})' if detail else ''}")
        lines.append("")

    lines += ["## Findings", ""]
    if not result.findings:
        lines += ["No findings. 🎉", ""]
    for f in result.findings:
        loc = f" · `{f.file}:{f.line}`" if f.file and f.line else ""
        tool = f" · tool `{f.tool}`" if f.tool else ""
        lines += [
            f"### {_ICON[f.severity.value]} {f.id} · {f.severity.value} · {f.title}",
            "",
            f"*{f.category.value}* · source **{f.source.value}** · confidence {f.confidence:.0%}{tool}{loc}"
            + (f" · {f.owasp_llm_ref}" if f.owasp_llm_ref else ""),
            "",
        ]
        if f.evidence:
            lines += ["**Evidence**", "", _fence(f.evidence), ""]
        if f.why:
            lines += [f"**Why it matters:** {f.why}", ""]
        if f.fix:
            lines += [f"**Fix:** {f.fix}", ""]

    if result.tool_verdicts:
        lines += ["## Tools", "", "| Tool | Verdict | Score | Claimed behavior |", "|---|---|---|---|"]
        for v in result.tool_verdicts:
            lines.append(f"| `{v.tool}` | {v.verdict} | {v.score:.2f} | {v.claimed_behavior or '—'} |")
        lines.append("")
    lines.append("_Generated by MCPGuard._")
    return "\n".join(lines)
